-- 기존 revoked 세션의 폐기 사유를 'rotated'로 백필한다.
--
-- 왜 필요한가: 0045가 컬럼을 추가하면 그 이전에 폐기된 행은 전부 NULL이 된다.
-- auth.service는 NULL을 "판단 근거 없음"으로 보고 기존 동작(유예 창 밖 재제시 →
-- 전 세션 무효화)을 유지하는데, 그게 바로 지금 사용자가 겪는 자동 로그아웃의
-- 원인이다. 백필하지 않으면 **배포 직후에도 한 번은 더 로그인이 풀린다** —
-- 클라이언트가 들고 있는 stale 토큰이 이 NULL 행 중 하나일 수 있기 때문이다.
-- 실측(2026-08-07): 운영 user_sessions 465행 중 460이 revoked 상태였다.
--
-- 왜 'rotated'로 채우는 것이 안전한가:
--   1) 이 행들의 절대다수는 회전으로 죽은 것이다. 로그아웃은 드물고(실사용 2인),
--      비밀번호 변경은 실측상 없었다.
--   2) logout으로 죽은 행이 섞여 있어도 로그아웃 무효화 문제는 생기지 않는다.
--      그 행들은 이미 24시간(REFRESH_REUSE_GRACE_MS)을 훨씬 넘겼으므로 유예를 받지
--      못하고, 'rotated' 경로에서도 그 요청만 401로 거절된다. 되살아나지 않는다.
--   3) 새로 발생하는 폐기는 애플리케이션이 사유를 정확히 기록하므로, 이 백필은
--      일회성 과거 정리이고 이후 판정 정확도를 낮추지 않는다.
--
-- 활성 세션(revoked_at IS NULL)은 건드리지 않는다.
UPDATE "user_sessions"
SET "revoked_reason" = 'rotated'
WHERE "revoked_at" IS NOT NULL
  AND "revoked_reason" IS NULL;
