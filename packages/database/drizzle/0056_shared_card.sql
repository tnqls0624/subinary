-- ## 왜
--
-- 카드 승인 문자에는 "누가 그었는지"가 없다. 실측으로 확정했다: 마스킹 이름 토큰은
-- 206건 중 41건에만 있고 발급사별 distinct=1(카드마다 상수), 카드번호 뒤 4자리는
-- 206건 전부 NULL이다. 그래서 거래의 `member_id`는 문자를 전달한 **폰의 주인**이고
-- (`registered_devices.member_id`), 한 카드의 문자는 한 대에만 도착하므로 부부가 함께
-- 쓰는 카드는 지출이 한 사람에게 전부 몰린다(실측 76.4% vs 23.6%).
--
-- ## 무엇을 하지 않는가
--
-- 금액을 지분으로 쪼개지 않는다. 50/50은 계산 결과가 아니라 **가정**이고, 그것을 실측
-- 금액 옆에 같은 서식으로 놓으면 왜곡을 없애는 대신 보이지 않게 만드는 것이다. 게다가
-- 소수 지분은 집계마다 강제하는 KRW 정수 불변식(`assertKrwInteger`)과 "거래 1건 =
-- member 1명" 규약을 둘 다 깨야 한다.
--
-- 거래 행도 건드리지 않는다(가산형). 집계가 조인 시점에 이 플래그를 읽으므로 켜는 순간
-- 과거까지 일관되게 바뀌고, 되돌리기는 플래그를 끄는 것으로 끝난다 — UPDATE가 없는
-- 설계가 소급을 가장 안전하게 만든다.
--
-- ## 되돌림
--
--   ALTER TABLE "payment_cards" DROP COLUMN IF EXISTS "is_shared";
--
-- 이 컬럼은 파생값이 아니라 사용자의 선언이므로, 지우면 그 선언이 사라진다. 집계는
-- 즉시 종전(소유자 귀속) 동작으로 돌아간다.
-- =============================================================================

ALTER TABLE "payment_cards"
  ADD COLUMN IF NOT EXISTS "is_shared" boolean DEFAULT false NOT NULL;
