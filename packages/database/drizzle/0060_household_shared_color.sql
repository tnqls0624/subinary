-- 공용 카드 결제의 표시 색 (가구 단위 설정).
--
-- 왜 필요한가: 공용 버킷은 지금 항상 중립 회색이다. 그 선택에는 이유가 있었다 —
-- "색이 곧 누구를 뜻하므로, 귀속을 보류한 거래에 특정 색을 주면 화면이 이름(공용)과
-- 다른 답을 말한다"(transactions/page.tsx). 하지만 그 우려는 **공용이 사람 색 팔레트에서
-- 임의로 배정될 때** 성립한다. 사용자가 직접 하나를 고르면 그 색은 "공용"이라는 하나의
-- 값을 가리키므로 화면이 두 답을 말하지 않는다.
--
-- 왜 가구 단위인가: 공용은 가구에 하나뿐인 묶음이고, 구성원 색(`household_members.color`)도
-- 가구 공통이다. 사용자별로 두면 같은 화면을 보는 가족이 서로 다른 색을 보게 된다.
--
-- NULL은 "고르지 않음"이고 종전 회색을 유지한다 — 기본 동작을 바꾸지 않는다.
-- 값 검증은 애플리케이션(`memberColorSchema`)이 한다. CHECK 제약을 걸지 않는 이유는
-- 팔레트에 색을 추가할 때 마이그레이션이 필요해지기 때문이고, 같은 이유로
-- `household_members.color`도 제약 없는 text다(그 결정과 일치시킨다).
ALTER TABLE households ADD COLUMN IF NOT EXISTS shared_color text;
