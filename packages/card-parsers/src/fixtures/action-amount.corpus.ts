/**
 * 금액 증거 shadow 코퍼스 — ADR-0027 롤아웃 3단계.
 *
 * 두 가지를 한 곳에 모은다.
 *
 * 1. **기존 픽스처 전수**: 지금 통과 중인 테스트(shinhan/kookmin/toss/dispatch/
 *    recipe/spans/decline-reason)에 들어 있는 실제·합성 문자를 **원문 그대로** 옮겼다.
 *    `legacyAmount`는 기존 파서가 실제로 내놓는 값이며, 이 값이 바뀌면 그건 회귀다
 *    (ADR-0027 롤아웃 3단계 전환 조건: "기존 정상 KRW 결과의 금액 delta 0건").
 *    공백·개행을 바꾸지 말 것 — 일부는 DB `card_sms_events`에서 그대로 가져온 원문이다.
 *
 * 2. **D-4 픽스처**: ADR-0027이 요구하는 광고·한도·누적 전후순서 negative와, 그
 *    게이트가 정상 승인을 잡아먹지 않는지 보는 positive.
 *
 * `kind`의 의미:
 * - `positive` — 실제 카드 승인/취소. 새 추출기가 **같은 금액**을 내야 한다.
 * - `negative` — D-4 계열(광고·한도·누적). 새 추출기가 거래 금액을 확정하면 안 되거나
 *   (`rejected_non_transaction`) 판촉이 아닌 실제 승인액을 골라야 한다.
 * - `non_card` — 비카드 문자. 게이트가 이미 막고 있으며(`routed=false`) 이 모듈의
 *   책임이 아니다. 게이트가 풀렸을 때 드러나도록 함께 재생만 한다.
 */
import type { ActionAmountStatus } from '../action-amount.js';

export interface CorpusEntry {
  readonly id: string;
  /** 원문이 어디서 왔는지(기존 테스트 파일 / 이번에 추가한 D-4). */
  readonly origin: string;
  readonly kind: 'positive' | 'negative' | 'non_card';
  readonly sender: string;
  readonly content: string;
  readonly receivedAt: Date;
  /**
   * 기존 파서(`parseCardSms`)가 내놓는 금액 — **측정된 기준값**이지 기대값이 아니다.
   * 이번 변경은 기존 경로를 건드리지 않으므로 전부 그대로여야 한다.
   */
  readonly legacyAmount?: number;
  readonly legacyCurrency?: string;
  /** 새(액션 결박) 추출기의 기대 상태·금액. */
  readonly expectedStatus: ActionAmountStatus;
  readonly expectedAmount?: number;
  readonly expectedCurrency?: string;
}

const at = (iso: string): Date => new Date(iso);

