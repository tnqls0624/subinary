/* ---------------------------------------------------------------------------
 * 비카드 문자 배제 게이트 — 파서 공용.
 *
 * 카드 결제가 아닌 문자(계좌 입출금·이체, 요금 '결제 예정'·청구 안내)는 금액+액션
 * 형태가 카드 승인과 똑같아서, 게이트가 없으면 approval 거래로 승격된다. 승격된
 * 유령 거래는 그 달 총액을 조용히 부풀리고, 원문이 카드 문자가 아니라 어디서 왔는지
 * 추적하기도 어렵다.
 *
 * 오배제(정상 승인 문자를 거부)의 대가는 `parse_failed` → 검토 화면 노출이므로
 * 복구 가능하다. 그래서 "오탐 > 미탐" 비대칭이 성립하고, 게이트는 보수적으로 둔다.
 * ------------------------------------------------------------------------- */

/**
 * 은행 거래·청구성 문구. **`잔액`을 포함하지 않는다** — 발급사가 확실한 문자에서
 * 잔액 라인은 체크카드 승인 알림의 정상 구성 요소다(토스뱅크 파서가 같은 이유로
 * 잔액 배제를 풀었다: `46,460원 결제 | 가맹점 ⏎ 잔액 109,798원`).
 *
 * {@link GenericCardParser}는 이보다 엄격한 자체 규칙을 쓴다(발급사 키워드가 없는
 * 문자까지 흡수하므로 잔액 통지도 걸러야 한다).
 */
const BANK_OR_BILLING_RE = /(입금|출금|이체|송금|결제\s*예정|청구|대출)/;

/**
 * 명시적 카드 거절/실패 통지. 이 문구가 있으면 배제 규칙을 **우회한다**.
 *
 * 왜 우회가 안전한가: "오탐 > 미탐" 비대칭은 **approval에만** 성립한다. 거절 문자는
 * `transactionType='declined'`로 판정되고 승격 파이프라인이 건너뛰므로
 * (`card-sms-parse.processor` §1.1) 오탐의 대가는 "실패 목록에 항목 하나"다.
 *
 * 왜 우회가 필요한가: 거절 **사유가 곧 비카드 단어**다 — `잔액이 부족해요`,
 * `한도 초과`. 두 규칙이 구조적으로 충돌해서, 사유가 적힌 문자일수록 거부된다.
 */
export const DECLINE_NOTICE_RE =
  /(승인\s*거[절부]|승인\s*불가|승인불가|결제\s*실패|승인\s*실패)/;

/**
 * 발급사 전용 파서(신한/KB)의 배제 판정 — 발급사 키워드가 있어도 카드 결제가
 * 아닌 문자면 `true`.
 *
 * 전용 파서의 `supports()`는 원래 발급사 키워드만 봤다. 그래서
 * `KB국민카드 결제 예정 금액 1,200,000원`(청구 예고)이 **approval 1,200,000원**으로
 * 승격됐다 — '결제'가 액션으로 인식되기 때문이다(ADR-0026 검증 중 발견).
 * `신한은행 자동이체 출금`도 같은 계열이다.
 *
 * 거절 통지는 우회한다(위 {@link DECLINE_NOTICE_RE}).
 */
export function isNonCardNotice(content: string): boolean {
  if (DECLINE_NOTICE_RE.test(content)) return false;
  return BANK_OR_BILLING_RE.test(content);
}
