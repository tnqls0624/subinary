/* ---------------------------------------------------------------------------
 * 앱 안에서 몇 번 이동했는가 (뒤로가기 판정용)
 *
 * 문제: `PageBackHeader`의 뒤로가기가 `/more` 고정이었다. `/todo`에서 `/declines`로
 * 들어간 사용자가 뒤로 누르면 `/more`로 튀어 길을 잃는다 — 자기가 온 길이 아니다.
 *
 * 해결은 브라우저 뒤로가기지만, **딥링크로 그 화면을 처음 연 경우**(푸시 알림·공유
 * 링크·앱 콜드스타트)에는 돌아갈 앱 화면이 없어 아무 일도 안 일어나거나 앱 밖으로
 * 나간다. 그래서 "앱 안에서 한 번이라도 이동했는가"를 세어 두고, 이동한 적이 있을
 * 때만 `router.back()`을 쓰고 아니면 지정된 경로로 밀어 준다.
 *
 * `window.history.length`를 쓰지 않는 이유: 그 값은 탭 전체의 세션 기록이라 다른
 * 사이트에서 넘어온 경우에도 1보다 크다 — 앱 안 이동 여부를 알려주지 못한다.
 *
 * 모듈 스코프 카운터인 이유: App Router의 클라이언트 레이아웃은 라우트 전환에도
 * 유지되지만 컴포넌트 상태에 두면 리마운트로 날아간다. 새로고침(하드 내비게이션)
 * 에서는 0으로 돌아가는데, 그것이 정확히 "딥링크로 방금 연 화면"의 상태다.
 * ------------------------------------------------------------------------- */

let inAppNavigations = 0;

/** 앱 내 경로가 바뀔 때마다 1회 호출(앱 셸 레이아웃이 배선한다). */
export function noteInAppNavigation(): void {
  inAppNavigations += 1;
}

/**
 * 브라우저 뒤로가기가 **앱 안의 이전 화면**으로 갈 수 있는가.
 *
 * 첫 진입도 1회로 세므로 기준은 `> 1`이다 — 1이면 이 화면이 앱에서 처음 그린
 * 화면(딥링크·새로고침)이라는 뜻이다.
 */
export function canGoBackInApp(): boolean {
  return inAppNavigations > 1;
}

/** 테스트 전용 — 카운터를 초기화한다. */
export function resetInAppNavigations(): void {
  inAppNavigations = 0;
}
